import * as fs from 'fs/promises';
import * as path from 'path';

// Artifacts are archived after being accepted
// But if they are just accepted and not yet archived, they might be in REVIEW_DIR.
// Alternatively, maybe they are already in ARCHIVE_DIR? 
// The cleanup script moves accepted items to ARCHIVE_DIR.
// So we should probably scan ARCHIVE_DIR for accepted items that haven't been scaffolded yet.
// Wait, we can scan both, or we can assume scaffold-bridge runs on ARCHIVE_DIR.

const ARCHIVE_DIR = path.join(process.cwd(), 'data', 'archive');
const MANIFEST_OUTPUT_DIR = path.join(process.cwd(), 'data', 'scaffold-manifests');

interface ReviewArtifact {
  id?: string;
  type?: string;
  review_state?: 'pending' | 'accepted' | 'rejected';
  created_at?: string;
  scaffolded?: boolean;
  [key: string]: any;
}

interface ScaffoldManifest {
  target_house: string;
  template_id: string;
  app_id: string;
  display_name: string;
  description: string;
  variables: Record<string, any>;
  source_artifact_id: string;
}

async function ensureDirectoryExists(dir: string) {
  try {
    await fs.access(dir);
  } catch {
    await fs.mkdir(dir, { recursive: true });
  }
}

async function scanDirectory(dir: string): Promise<string[]> {
  const files: string[] = [];
  try {
    const entries = await fs.readdir(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        files.push(...await scanDirectory(fullPath));
      } else if (entry.isFile() && entry.name.endsWith('.json')) {
        files.push(fullPath);
      }
    }
  } catch (error: any) {
    if (error.code !== 'ENOENT') {
      console.error(`Error scanning directory ${dir}:`, error);
    }
  }
  return files;
}

function kebabCase(str: string): string {
  return str
    .replace(/([a-z])([A-Z])/g, '$1-$2')
    .replace(/[\s_]+/g, '-')
    .toLowerCase();
}

export async function runScaffoldBridge() {
  console.log(`Starting Scaffold Bridge...`);
  await ensureDirectoryExists(MANIFEST_OUTPUT_DIR);

  // We scan the archive dir for accepted items
  const files = await scanDirectory(ARCHIVE_DIR);
  let processedCount = 0;

  for (const filePath of files) {
    try {
      const content = await fs.readFile(filePath, 'utf-8');
      const artifact = JSON.parse(content) as ReviewArtifact;

      if (
        artifact.review_state === 'accepted' &&
        artifact.type === 'vega.skill-candidate' &&
        !artifact.scaffolded
      ) {
        console.log(`Processing artifact ${artifact.id}...`);
        
        const candidateName = artifact.name || 'Unknown Skill';
        const candidateDesc = artifact.description || 'Generated by Vega Labs';
        
        // Generate scaffold manifest
        const manifest: ScaffoldManifest = {
          target_house: 'houses/tier2-orchestrator', // Default to the orchestrator house, or derive from artifact
          template_id: 'default-skill-template', // Assuming a default template id
          app_id: kebabCase(candidateName),
          display_name: candidateName,
          description: candidateDesc,
          variables: {
            capabilities: artifact.capabilities || [],
            source: artifact.source || 'vega-mining'
          },
          source_artifact_id: artifact.id || 'unknown'
        };

        const manifestFileName = `manifest-${manifest.app_id}-${Date.now()}.json`;
        const manifestPath = path.join(MANIFEST_OUTPUT_DIR, manifestFileName);
        
        await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2), 'utf-8');
        console.log(`[GENERATED] ${manifestFileName}`);

        // Mark as scaffolded so we don't process it again
        artifact.scaffolded = true;
        await fs.writeFile(filePath, JSON.stringify(artifact, null, 2), 'utf-8');
        
        processedCount++;
      }
    } catch (err: any) {
      console.error(`Error processing file ${filePath}:`, err.message);
    }
  }

  console.log(`\nScaffold Bridge Summary:`);
  console.log(`Generated Manifests: ${processedCount}`);
}

// Run if called directly
if (import.meta.url === `file://${process.argv[1]}`) {
  runScaffoldBridge().catch(console.error);
}
